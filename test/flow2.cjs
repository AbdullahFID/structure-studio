const { open, shot, sleep, send, idle } = require('./harness.cjs');
(async () => {
  const { browser, page, logs } = await open();
  await page.waitForFunction(() => !document.querySelector('.tab .spin'), null, { timeout: 30000 });
  await page.click('button.tool:has-text("Compare")');
  await sleep(1500);
  await shot(page, '07-compare');
  await page.click('button.tool:has-text("Compare")');
  // New project and shed flow
  await page.click('button:has-text("New project")');
  await sleep(700);
  await shot(page, '08-new');
  await page.click('.example >> nth=0');
  await sleep(200);
  await page.keyboard.press('Enter');
  await page.waitForSelector('.spec:not(.spec--locked)', { timeout: 5000 });
  await sleep(500);
  await shot(page, '09-checkpoint');
  await page.click('.spec .btn--primary');
  await sleep(1300);
  await shot(page, '10-generating');
  await idle(page, 40000);
  await sleep(500);
  await shot(page, '11-shed');
  await send(page, 'Switch it to steel');
  await sleep(1400);
  await shot(page, '12-switching');
  await idle(page, 40000);
  await shot(page, '13-steel');
  await send(page, 'Add a timber version as a new option');
  await idle(page, 40000);
  await shot(page, '14-added');
  await page.click('.pal-btn[aria-label="Show walls and roof"]');
  await sleep(800);
  await shot(page, '15-envelope');
  console.log(logs.join('\n') || 'NO LOGS');
  await browser.close();
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
